# FATIAMENTO

nome = "Eduardo Santos da Silva"

print(nome[0]) # Irá retornar a letra E

print(nome[:7]) # Ele irá ter um start retornar até indice 8, nesse caso seria meu nome inteiro

print(nome[8:]) # Ele terá um start a partir do indice 9 até o final

print(nome[8:16]) # Ele irá passar o intervalo desses indices

print(nome[8:16:2]) # Ele vai me informar 3 letras entre os indices 10:16

print(nome[:]) # Nesse caso como tem apenas o start, ele vai informar o nome inteiro

print(nome[::-1]) # Ele vai informar o nome de trás para frente. Mais conhecido como espelhamento