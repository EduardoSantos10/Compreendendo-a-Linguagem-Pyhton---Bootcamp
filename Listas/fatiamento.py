lista = ["p", "y", "t", "h", "o", "n"]

print(lista[2:]) # Ele vai imprimir uma mensagem com start no segundo indice
print(lista[:2]) # Ele vai imprimir uma mensagem com os dois primeiros indices
print(lista[1:3]) # Ele vai imprimir uma mensagem com o indice 1
print(lista[0:3:2]) # Ele tem o start em 0, depois vai pular de 2 em 2
print(lista[::]) # Ele vai imprimir todas os valores
print(lista[::-1]) # Ele vai inverter os valores da frente para trás