# LISTAS ANINHADAS: MATRIZ BIDIMENSIONAL
matriz = [
    [1, "a", 2],
    ["b", 3, 4],
    [6, 5, "c"]
]

print(matriz[0]) # Vai imprimir a primeiro linha
print(matriz[0][0]) # Vai imprimir o indice 1 da primeira linha
print(matriz[0][-1]) # Vai imprimir o  indice negativo da primeira linha
print(matriz[-1][-1]) # Vai imprimir o indice negativo do última linha
