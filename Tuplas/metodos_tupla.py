# METODO COUNT:
cores = ("vermelho", "azul", "verde", "azul",) # Ele va informar quantas vezes uma determinada palavra aparece

print(cores.count("vermelho"))
print(cores.count("azul"))
print(cores.count("verde"))


# METODO INDEX:
linguagens = ("python", "js", "c", "java", "csharp",) # Ele informa o indice do elemento

print(linguagens.index("java"))
print(linguagens.index("python"))


# METODO LEN:
linguagens = ("python", "js", "c", "java", "csharp",) # Ele informa quantos elementos aparece na tupla

print(len(linguagens))